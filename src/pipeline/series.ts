export interface FixtureDay {
  date: string;
  steps: number | null;
  distanceKm: number | null;
  activeMinutes: [number, number, number] | null;
  activeKcal: number | null;
  totalKcal: number | null;
  restingHr: number | null;
  hrv: number | null;
  respiratoryRate: number | null;
  spo2: [number, number, number] | null;
  tempDeviation: number | null;
  sleep: {
    asleep: number; awake: number; light: number; deep: number; rem: number;
    bedtime: string; wake: string;
  } | null;
}

const n = (s: string): number | null => (s === '' ? null : Number(s));
const trio = (s: string): [number, number, number] | null => {
  if (!s) return null;
  const p = s.split(',').map(Number);
  return [p[0], p[1], p[2]];
};

export function parseFixtureSeries(): FixtureDay[] {
  return PACKED_SERIES.trim().split('\n').map((line) => {
    const c = line.split('|');
    const sleepRaw = c[11];
    let sleep: FixtureDay['sleep'] = null;
    if (sleepRaw) {
      const p = sleepRaw.split(',');
      sleep = {
        asleep: Number(p[0]), awake: Number(p[1]), light: Number(p[2]),
        deep: Number(p[3]), rem: Number(p[4]), bedtime: p[5], wake: p[6],
      };
    }
    return {
      date: `${YEAR}-${c[0]}`,
      steps: n(c[1]),
      distanceKm: n(c[2]),
      activeMinutes: trio(c[3]),
      activeKcal: n(c[4]),
      totalKcal: n(c[5]),
      restingHr: n(c[6]),
      hrv: n(c[7]),
      respiratoryRate: n(c[8]),
      spo2: trio(c[9]),
      tempDeviation: n(c[10]),
      sleep,
    };
  });
}

